const pick=(arr,n)=>arr[((Number(n)||1)-1)%arr.length];

function selectTwo(prompt,correct,wrong,n,explanation){
  const labels=rotate([...correct,...wrong],n).slice(0,5);
  const set=new Set(correct);
  return {
    type:'multiple',questionType:'multiple_answer',prompt,
    instruction:'Выберите два верных варианта и запишите их номера.',
    options:labels.map((label,i)=>({value:String(i),label})),
    answer:labels.map((label,i)=>set.has(label)?String(i):null).filter(v=>v!==null),
    difficulty:Math.max(2,diff(n)),explanation,
    solutionSteps:['Определите реакционный центр или функциональную группу.','Проверьте условия каждой реакции.','Выберите ровно две верные позиции.']
  };
}

