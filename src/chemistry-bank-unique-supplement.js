    const task=`К ${m1} г ${w1}%-ного раствора NaOH добавили ${m2} г ${w2}%-ного раствора HCl. Кислота и щёлочь взяты в стехиометрическом соотношении. Найдите массовую долю NaCl в конечном растворе, %.`;
