'use strict';
const base=require('./chemistry-bank-extended');
const {extended}=require('./chemistry-bank-utils');

function build33(n){
  n=Math.max(1,Number(n)||1);
  if(((n-1)%10)+1!==6)return base[33](n);
  const criteria=[
    'По массовой доле кислорода корректно найдена молярная масса вещества.',
    'Использована общая формула предельного одноатомного спирта и найдено число атомов углерода.',
    'Записана правильная молекулярная формула и приведено обоснование.'
  ];
  const model='Для предельного одноатомного спирта CnH2n+2O молярная масса M=14n+18. Один атом O даёт массовую долю 16/M=0,2759, откуда M≈58 г/моль. 14n+18=58, n≈3. Формула C3H8O.';
  const item=extended(
    'Предельный одноатомный спирт содержит 27,59% кислорода по массе. Определите его молекулярную формулу и покажите расчёт.',
    model,n,
    'Здесь формулу находят не по продуктам сгорания, а по массовой доле кислорода и общей формуле предельного одноатомного спирта.',
    criteria,
    ['Запишите общую формулу предельного одноатомного спирта CnH2n+2O.','Выразите молярную массу через n: M=14n+18.','Используйте w(O)=16/M и найдите M.','Определите n и запишите молекулярную формулу.']
  );
  item.content={...(item.content||{}),formulaScenario:'oxygen-mass-fraction-alcohol'};
  return item;
}

module.exports={33:build33};
