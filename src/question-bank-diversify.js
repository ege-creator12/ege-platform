function diversifyQuestion(item,{n=1,line=0,subject=''}={}){
 const out=clone(item||{});
 const round=Math.floor((Math.max(1,Number(n)||1)-1)/10);
 if(round===0)return out;
 const type=String(out.questionType||out.type||'').toLowerCase();
 const frames=FRAMES[type]||FRAMES.default;
 const frame=frames[(round-1)%frames.length];
 out.prompt=`${frame} ${String(out.prompt||'').trim()}`.trim();
 out.solutionSteps=[...(Array.isArray(out.solutionSteps)?out.solutionSteps:[]),'Сверьте итог с форматом ответа именно этой линии ЕГЭ.'];
 out.content={...(out.content||{}),presentationDiversified:true,subject,examLine:Number(line)||0};
 return out;
}

