function buildExtra(line,n){
  if(EXTENDED[line])return clone(EXTENDED[line][(n-1)%EXTENDED[line].length]);
  const seed=((n-1)%12)+1;
  const item=clone(build(line,seed));
  const type=item.questionType||item.type||'short_answer';
  const stems=STEMS[type]||STEMS.short_answer;
  const style=Math.floor((n-1)/12)%stems.length;
  item.prompt=`${stems[style]} ${item.prompt}`;
  item.difficulty=diff(n);
  item.solutionSteps=[...(item.solutionSteps||[]),'Проверьте, что ответ относится именно к формулировке этого варианта.'];
  return item;
}

