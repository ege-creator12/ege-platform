function promptFor(line,n){
  const list=topics[line];
  if(!list)return null;
  const topic=list[(n-1)%list.length];
  if(line===22)return `Спланируйте биологический эксперимент по теме «${topic}». Сформулируйте гипотезу, назовите независимую и зависимую переменные, контролируемые условия и принцип контрольной группы.`;
  if(line===23)return `${topic} Сформулируйте три вывода, которые прямо следуют из результатов, и не выходите за пределы данных.`;
  if(line===24)return `Объясните связь строения и функции на примере: ${topic}. Приведите три биологически корректных смысловых элемента.`;
  if(line===25)return `Объясните физиологический механизм: ${topic}. Покажите причинную связь между изменением, регуляцией и результатом.`;
  if(line===26)return `Объясните с позиций экологии и эволюции ситуацию: ${topic}. Постройте причинную цепь из четырёх смысловых элементов.`;
  return topic;
}

function buildExtra(line,n){
  const item=source.buildExtra(line,n);
  if(item&&(!item.prompt||!String(item.prompt).trim()))item.prompt=promptFor(Number(line),Number(n));
  return item;
}

