const variants=value=>{
  const s=String(value);
  const comma=s.includes('.')?s.replace('.',','):s;
  return comma===s?[]:[comma];
};
function selectTwo(prompt,correct,wrong,n,explanation){
  return multiple(prompt,correct,wrong,n,explanation,['Проверьте каждый вариант отдельно.','Выберите ровно две позиции, удовлетворяющие условию.']);
}
function ext(prompt,model,n,criteria,explanation='Покажите химически корректное решение и проверьте коэффициенты, единицы и условия.'){
  return extended(prompt,model,n,explanation,criteria);
}

