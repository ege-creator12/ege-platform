'use strict';

const diff=n=>1+((Number(n)||1)-1)%3;
const rotate=(arr,n)=>arr[((Number(n)||1)-1)%arr.length];

function multiple(prompt,good,bad,n,content={}){
  const all=[...good,...bad];
  const shift=((Number(n)||1)-1)%all.length;
  const shown=[...all.slice(shift),...all.slice(0,shift)];
  const goodSet=new Set(good);
  return {
    type:'multiple',
    questionType:'multiple_answer',
    prompt,
    instruction:'Выберите верные утверждения.',
    options:shown.map((label,i)=>({value:String(i),label})),
    answer:shown.map((label,i)=>goodSet.has(label)?String(i):null).filter(x=>x!==null),
    difficulty:diff(n),
    content,
    explanation:'Выберите только выводы, которые прямо следуют из условия и биологических закономерностей.',
    solutionSteps:['Проверьте каждое утверждение отдельно.','Отделите данные условия от предположений.','Запишите номера верных утверждений.']
  };
}

